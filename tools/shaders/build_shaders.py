"""Rebuilds the compiled shaders that the game embeds.

Each shader in SHADERS (shaders/<name>.frag.hlsl) is compiled offline, once,
to the three formats
SDL's GPU render driver can load, and each blob is embedded in a generated
header, so the game needs no shader compiler at run time:

  DXIL   (Direct3D 12)  dxc -T ps_6_0           (signed by DXC's validator)
  SPIR-V (Vulkan)       dxc -T ps_6_0 -spirv
  MSL    (Metal)        spirv-cross --msl on the SPIR-V

Outputs, all committed, per shader:
  src/engine/fx/generated/<Header>.h   the blobs as byte arrays
  shaders/<name>.sha256                sha256 of the source and blobs

Tools, from the official releases (DXC from Microsoft's DirectXShaderCompiler
or the LunarG Vulkan SDK, which also carries SPIRV-Cross):

  python3 tools/shaders/build_shaders.py --dxc /path/to/dxc \
      --spirv-cross /path/to/spirv-cross
  python3 tools/shaders/build_shaders.py --check   # blobs match the source?

Without the flags the tools are taken from DXC / SPIRV_CROSS, then
$VULKAN_SDK/bin, then PATH. --check rebuilds in a scratch folder and fails
when the committed header differs (the compilers are deterministic for a
given version; the versions used are recorded in the header). --only NAME
builds one shader.
"""

from __future__ import annotations

import argparse
import hashlib
import os
import shutil
import subprocess
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
GENERATED = ROOT / "src" / "engine" / "fx" / "generated"


@dataclass(frozen=True)
class Shader:
    name: str  # shaders/<name>.frag.hlsl, shaders/<name>.sha256
    header: str  # src/engine/fx/generated/<header>
    prefix: str  # C++ names: <prefix>_dxil, <prefix>_spirv, <prefix>_msl, <prefix>_entry

    @property
    def source(self) -> Path:
        return ROOT / "shaders" / f"{self.name}.frag.hlsl"

    @property
    def header_path(self) -> Path:
        return GENERATED / self.header

    @property
    def hashes_path(self) -> Path:
        return ROOT / "shaders" / f"{self.name}.sha256"


SHADERS = (
    Shader("postfx", "PostFxShaders.h", "postfx"),
    Shader("normal_light", "NormalLightShaders.h", "normal_light"),
)

# Child processes never open a console window on Windows.
HIDDEN: dict[str, Any] = {}
if sys.platform == "win32":
    HIDDEN["creationflags"] = subprocess.CREATE_NO_WINDOW

DXC_COMMON = ["-T", "ps_6_0", "-E", "main", "-HV", "2021", "-O3", "-Wno-ignored-attributes"]


def find(explicit: str | None, env: str, exe: str) -> str:
    candidates = [explicit, os.environ.get(env)]
    sdk = os.environ.get("VULKAN_SDK")
    if sdk:
        candidates.append(str(Path(sdk) / "bin" / exe))
    candidates.append(shutil.which(exe))
    for c in candidates:
        if c and Path(c).is_file():
            return c
    sys.exit(f"{exe} not found: pass --{exe}, set {env} or VULKAN_SDK, or put it on PATH")


def run(cmd: list[str]) -> str:
    done = subprocess.run(cmd, capture_output=True, text=True, check=False, **HIDDEN)  # nosec B603
    if done.returncode != 0:
        sys.exit(f"failed ({done.returncode}): {' '.join(cmd)}\n{done.stdout}{done.stderr}")
    return (done.stdout + done.stderr).strip()


def version(cmd: list[str]) -> str:
    text = run(cmd)
    return text.splitlines()[0].strip() if text else "unknown"


def c_array(name: str, data: bytes) -> str:
    lines = [f"inline constexpr unsigned char {name}[] = {{"]
    for i in range(0, len(data), 12):
        chunk = ", ".join(f"0x{b:02x}" for b in data[i : i + 12])
        lines.append(f"    {chunk},")
    lines.append("};")
    return "\n".join(lines)


def build(shader: Shader, dxc: str, spirv_cross: str, out_dir: Path) -> tuple[str, str]:
    source = shader.source
    dxil = out_dir / f"{shader.name}.frag.dxil"
    spv = out_dir / f"{shader.name}.frag.spv"
    msl = out_dir / f"{shader.name}.frag.msl"
    run([dxc, *DXC_COMMON, "-Fo", str(dxil), str(source)])
    run([dxc, *DXC_COMMON, "-spirv", "-fspv-target-env=vulkan1.0", "-Fo", str(spv), str(source)])
    run([spirv_cross, str(spv), "--msl", "--msl-version", "20100", "--output", str(msl)])
    if dxil.read_bytes()[4:20] == bytes(16):
        sys.exit("the DXIL is not signed (DXC's validator did not run): Direct3D 12 would reject it")

    blobs = {"dxil": dxil.read_bytes(), "spirv": spv.read_bytes(), "msl": msl.read_bytes()}
    digests = {"source": hashlib.sha256(source.read_bytes()).hexdigest()}
    digests.update({k: hashlib.sha256(v).hexdigest() for k, v in blobs.items()})
    tools = f"{version([dxc, '--version'])}; {version([spirv_cross, '--revision'])}"

    parts = [
        "// SPDX-FileCopyrightText: 2026 ShadowByte",
        "//",
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "//",
        "// clang-format off",
        f"// Generated by tools/shaders/build_shaders.py from shaders/{shader.name}.frag.hlsl;",
        "// do not edit. Rebuild with that script after changing the shader.",
        f"// Tools: {tools}",
    ]
    parts += [f"// sha256 {k}: {v}" for k, v in digests.items()]
    parts += [
        "",
        "#pragma once",
        "",
        "#include <cstddef>",
        "",
        "namespace fx::shaders {",
        "",
        c_array(f"{shader.prefix}_frag_dxil", blobs["dxil"]),
        "",
        c_array(f"{shader.prefix}_frag_spirv", blobs["spirv"]),
        "",
        "// MSL source text, without a terminating zero.",
        c_array(f"{shader.prefix}_frag_msl", blobs["msl"]),
        "",
        "// Entry points: SPIR-V-Cross renames main for Metal.",
        f'inline constexpr const char* {shader.prefix}_entry = "main";',
        f'inline constexpr const char* {shader.prefix}_entry_msl = "main0";',
        "",
        "} // namespace fx::shaders",
        "// clang-format on",
        "",
    ]
    header = "\n".join(parts)
    hashes = "".join(f"{v}  {k}\n" for k, v in digests.items())
    return header, f"# {tools}\n{hashes}"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dxc")
    ap.add_argument("--spirv-cross")
    ap.add_argument("--check", action="store_true", help="fail when the committed blobs differ from a rebuild")
    ap.add_argument("--only", choices=[s.name for s in SHADERS])
    args = ap.parse_args(argv)
    dxc = find(args.dxc, "DXC", "dxc")
    spirv_cross = find(args.spirv_cross, "SPIRV_CROSS", "spirv-cross")
    failed = 0
    for shader in SHADERS:
        if args.only and shader.name != args.only:
            continue
        with tempfile.TemporaryDirectory() as tmp:
            header, hashes = build(shader, dxc, spirv_cross, Path(tmp))
        path = shader.header_path
        if args.check:
            same = path.is_file() and path.read_text(encoding="utf-8") == header
            print(f"{'PASS' if same else 'FAIL'} shaders/{shader.name}: "
                  f"{'the committed blobs match the source' if same else 'rebuild them'}")
            failed += 0 if same else 1
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(header, encoding="utf-8", newline="\n")
        shader.hashes_path.write_text(hashes, encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(ROOT)} and {shader.hashes_path.relative_to(ROOT)}")
        print(hashes, end="")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
